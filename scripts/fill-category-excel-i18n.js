function cellText(cell) {
  if (!cell) return "";
  try {
    const t = cell.text;
    if (t != null && String(t).trim()) return String(t).trim();
  } catch (_) {}
  const v = cell.value;
  if (v == null) return "";
  if (typeof v === "string" || typeof v === "number") return String(v).trim();
  return "";
}

