function esc(s) {
  return String(s || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function clip(s, n) {
  const t = String(s || "").replace(/\s+/g, " ").trim();
  if (t.length <= n) return t;
  return t.slice(0, n - 1).trim() + "…";
}

function tokenize(name) {
  return String(name || "")
    .replace(/\s+/g, " ")
    .trim()
    .split(/(\s+|&|\/|,)/)
    .filter((t) => t && t !== " ");
}

function translateToken(token, lang) {
  if (token === "&") return AMP[lang] || "&";
  if (token === "/" || token === ",") return token;
  const key = token.toLowerCase();
  const hit = WORDS[key];
  if (hit && hit[lang]) {
    if (/^[A-Z]/.test(token) && lang !== "de") {
      const w = hit[lang];
      return w.charAt(0).toUpperCase() + w.slice(1);
    }
    if (lang === "de") return hit[lang];
    return hit[lang];
  }
  return token;
}

function translateName(en, lang) {
  if (lang === "en") return en;
  let rest = ` ${en.trim()} `;
  const phrases = Object.keys(PHRASES).sort((a, b) => b.length - a.length);
  const slots = [];
  phrases.forEach((p, i) => {
    const re = new RegExp(p.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "ig");
    rest = rest.replace(re, () => {
      const mark = `§P${i}§`;
      slots.push({ mark, text: PHRASES[p][lang] });
      return mark;
    });
  });
  const translated = rest
    .split(/(\s+|&|\/|,|§P\d+§)/)
    .filter(Boolean)
    .map((t) => {
      const slot = slots.find((s) => s.mark === t);
      if (slot) return slot.text;
      if (/^\s+$/.test(t)) return " ";
      return translateToken(t.trim() || t, lang);
    })
    .join("")
    .replace(/\s+/g, " ")
    .replace(/\s+&\s+/g, lang === "tr" ? " ve " : " & ")
    .replace(/\s+,/g, ",")
    .trim();
  return translated || en;
}

function keywordsFromName(name) {
  const bits = String(name)
    .toLowerCase()
    .replace(/[&/(),]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 1);
  const extra = [name.toLowerCase(), bits.slice(0, 3).join(" ")].filter(Boolean);
  return [...new Set([...extra, ...bits])].slice(0, 8).join(", ");
}

function descriptionHtml(lang, name) {
  const c = COPY[lang];
  return `<h2>${esc(c.h2(name))}</h2>\n<p>${c.p1(name)}</p>\n<p>${c.p2(name)}</p>`;
}

function fillRow(ws, r, names) {
  for (const lang of LANGS) {
    const n = names[lang];
    ws.getRow(r).getCell(COL[`name_${lang}`]).value = n;
    ws.getRow(r).getCell(COL[`description_${lang}`]).value = descriptionHtml(lang, n);
    ws.getRow(r).getCell(COL[`seo_title_${lang}`]).value = COPY[lang].seoTitle(n);
    ws.getRow(r).getCell(COL[`seo_description_${lang}`]).value = COPY[lang].seoDesc(n);
    ws.getRow(r).getCell(COL[`seo_keywords_${lang}`]).value = keywordsFromName(n);
  }
}

async function main() {
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(FILE);
  const ws = wb.getWorksheet("Categories") || wb.worksheets[0];
  const last = Math.max(ws.actualRowCount || 0, ws.rowCount || 0);
  let filled = 0;
  let skipped = 0;
  for (let r = 3; r <= last; r++) {
    const row = ws.getRow(r);
    const en = cellText(row.getCell(COL.name_en));
    if (!en) {
      skipped++;
      continue;
    }
    const names = { en };
    for (const lang of LANGS) {
      if (lang === "en") continue;
      names[lang] = translateName(en, lang);
    }
    fillRow(ws, r, names);
    filled++;
    if (filled % 500 === 0) console.log("filled", filled);
  }
  console.log("writing", filled, "rows, skipped", skipped);
  await wb.xlsx.writeFile(FILE);
  console.log("saved", FILE);
}

