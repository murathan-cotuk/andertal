function getCountryName(raw, locale) {
  if (!raw) return ''
  const trimmed = String(raw).trim()
  const upper = trimmed.toUpperCase()
  const loc = resolvePdfLocale(locale)

  if (upper.length === 2 && COUNTRY_NAMES[upper]) {
    return COUNTRY_NAMES[upper][loc] || COUNTRY_NAMES[upper].en || trimmed
  }

  const lower = trimmed.toLowerCase()
  const iso = COUNTRY_REVERSE[lower]
  if (iso && COUNTRY_NAMES[iso]) {
    return COUNTRY_NAMES[iso][loc] || COUNTRY_NAMES[iso].en || trimmed
  }

  return trimmed
}

